#!/usr/bin/env python3
"""Generate crates/kernway-wire/src/saslprep_tables.rs: the stringprep
(RFC 3454) tables SASLprep (RFC 4013) uses, and NFKC data — all Unicode 3.2,
as RFC 3454 fixes. Python's `stringprep` module and `unicodedata.ucd_3_2_0`
implement exactly those tables, so they are the source here.

    python3 crates/kernway-wire/tools/gen_saslprep.py > crates/kernway-wire/src/saslprep_tables.rs
"""
import stringprep
import unicodedata

U = unicodedata.ucd_3_2_0
MAX = 0x10FFFF
SBASE, SCOUNT = 0xAC00, 11172  # Hangul syllables: done by arithmetic


def ranges(pred):
    out, start = [], None
    for cp in range(MAX + 2):
        hit = cp <= MAX and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def ch(cp):
    return chr(cp)


def prohibited(cp):
    c = ch(cp)
    return (
        stringprep.in_table_a1(c)
        or stringprep.in_table_c12(c)
        or stringprep.in_table_c21_c22(c)
        or stringprep.in_table_c3(c)
        or stringprep.in_table_c4(c)
        or stringprep.in_table_c5(c)
        or stringprep.in_table_c6(c)
        or stringprep.in_table_c7(c)
        or stringprep.in_table_c8(c)
        or stringprep.in_table_c9(c)
    )


def rust_ranges(name, rs, doc):
    lines = [f"/// {doc}", f"pub(crate) static {name}: &[(u32, u32)] = &["]
    row = []
    for a, b in rs:
        row.append(f"(0x{a:X}, 0x{b:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def rust_str(s):
    return '"' + "".join(f"\\u{{{ord(c):X}}}" for c in s) + '"'


def main():
    out = [
        "//! Generated by `tools/gen_saslprep.py` from Unicode 3.2 (RFC 3454) — do not edit.",
        "",
        "#![allow(clippy::unreadable_literal)]",
        "",
    ]
    surrogate = lambda cp: 0xD800 <= cp <= 0xDFFF
    out.append(rust_ranges("MAP_TO_NOTHING", ranges(lambda cp: not surrogate(cp) and stringprep.in_table_b1(ch(cp))), "RFC 3454 B.1: removed."))
    out.append(rust_ranges("NON_ASCII_SPACE", ranges(lambda cp: not surrogate(cp) and stringprep.in_table_c12(ch(cp))), "RFC 3454 C.1.2: mapped to U+0020."))
    out.append(rust_ranges("PROHIBITED", ranges(lambda cp: surrogate(cp) or prohibited(cp)), "RFC 3454 A.1 (unassigned) and C.1.2, C.2.1, C.2.2, C.3–C.9: refused."))
    out.append(rust_ranges("RAND_AL_CAT", ranges(lambda cp: not surrogate(cp) and stringprep.in_table_d1(ch(cp))), "RFC 3454 D.1: right-to-left characters."))
    out.append(rust_ranges("L_CAT", ranges(lambda cp: not surrogate(cp) and stringprep.in_table_d2(ch(cp))), "RFC 3454 D.2: left-to-right characters."))

    # Canonical combining classes.
    ccc = [(cp, U.combining(ch(cp))) for cp in range(MAX + 1) if not surrogate(cp) and U.combining(ch(cp))]
    out.append("/// Non-zero canonical combining classes, sorted by code point.")
    out.append("pub(crate) static CCC: &[(u32, u8)] = &[")
    for i in range(0, len(ccc), 8):
        out.append("    " + ", ".join(f"(0x{a:X}, {b})" for a, b in ccc[i : i + 8]) + ",")
    out.append("];")

    # Full compatibility decompositions (NFKD of each character), Hangul aside.
    dec = []
    for cp in range(MAX + 1):
        if surrogate(cp) or SBASE <= cp < SBASE + SCOUNT:
            continue
        d = U.normalize("NFKD", ch(cp))
        if d != ch(cp):
            dec.append((cp, d))
    out.append("/// Full compatibility decompositions (NFKD), sorted by code point; Hangul syllables are computed.")
    out.append("pub(crate) static DECOMPOSE: &[(u32, &str)] = &[")
    for cp, d in dec:
        out.append(f"    (0x{cp:X}, {rust_str(d)}),")
    out.append("];")

    # Primary composites: pairs that NFC recombines (exclusions, singletons and
    # non-starter decompositions left out), Hangul aside.
    comp = []
    for cp in range(MAX + 1):
        if surrogate(cp) or SBASE <= cp < SBASE + SCOUNT:
            continue
        d = U.decomposition(ch(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        if U.normalize("NFC", ch(cp)) != ch(cp):
            continue
        comp.append((parts[0], parts[1], cp))
    comp.sort()
    out.append("/// Canonical compositions (first, second) → composite, sorted by the pair.")
    out.append("pub(crate) static COMPOSE: &[(u32, u32, u32)] = &[")
    for i in range(0, len(comp), 4):
        out.append("    " + ", ".join(f"(0x{a:X}, 0x{b:X}, 0x{c:X})" for a, b, c in comp[i : i + 4]) + ",")
    out.append("];")
    print("\n".join(out))


main()
