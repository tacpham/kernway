//! Oracle SQL dialect.

use kernway_orm_core::{
    dialect::SqlDialect,
    entity::{ColumnDef, ColumnType},
};

/// Oracle Database (23ai+) SQL dialect.
#[derive(Debug, Clone, Copy, Default)]
pub struct OracleDialect;

impl SqlDialect for OracleDialect {
    fn name(&self) -> &'static str {
        "oracle"
    }

    fn placeholder(&self, index: usize) -> String {
        format!(":{index}")
    }

    /// Identity columns are declared in [`column_ddl`](Self::column_ddl).
    fn auto_increment_keyword(&self) -> &'static str {
        ""
    }

    fn supports_returning(&self) -> bool {
        true
    }

    fn col_type_ddl(&self, col_type: &ColumnType) -> &'static str {
        match col_type {
            ColumnType::Integer => "NUMBER(10)",
            ColumnType::BigInt => "NUMBER(19)",
            ColumnType::Boolean => "BOOLEAN",
            ColumnType::Float => "BINARY_DOUBLE",
            // A String column holds up to 4000 bytes (VARCHAR2's limit unless
            // the database runs with MAX_STRING_SIZE = EXTENDED); longer text
            // needs a CLOB column declared by hand.
            ColumnType::Text | ColumnType::Unknown => "VARCHAR2(4000)",
            ColumnType::Timestamp => "TIMESTAMP",
            ColumnType::Json => "JSON",
            ColumnType::Binary => "BLOB",
        }
    }

    /// Generated keys are identity columns; text keys / unique columns are
    /// `VARCHAR2(255)`.
    fn column_ddl(&self, col: &ColumnDef) -> String {
        if col.primary_key && col.auto {
            return format!("{} GENERATED BY DEFAULT ON NULL AS IDENTITY", self.col_type_ddl(&col.col_type));
        }
        let text = matches!(col.col_type, ColumnType::Text | ColumnType::Unknown);
        if text && (col.primary_key || col.unique) {
            "VARCHAR2(255)".to_string()
        } else {
            self.col_type_ddl(&col.col_type).to_string()
        }
    }

    fn lock_for_update_suffix(&self) -> &'static str {
        "FOR UPDATE"
    }

    fn ping_sql(&self) -> &'static str {
        "SELECT 1 FROM dual"
    }

    fn empty_string_is_null(&self) -> bool {
        true
    }

    fn max_bind_params(&self) -> usize {
        65_535
    }

    /// ORA-01795: at most 1,000 expressions in a list.
    fn max_in_list(&self) -> usize {
        1_000
    }

    fn limit_offset(&self, limit: Option<u64>, offset: u64) -> String {
        let mut s = String::new();
        if offset > 0 || limit.is_some() {
            s.push_str(&format!(" OFFSET {offset} ROWS"));
        }
        if let Some(n) = limit {
            s.push_str(&format!(" FETCH NEXT {n} ROWS ONLY"));
        }
        s
    }
}
