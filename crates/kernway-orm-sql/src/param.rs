//! Neutral bind values and the entity <-> parameter mapping.

use kernway_orm_core::{
    entity::{ColumnDef, ColumnType, Entity},
    error::OrmError,
};
use serde::Serialize;

/// A bound parameter value, before a backend turns it into its wire form.
#[derive(Debug, Clone, PartialEq)]
pub enum Param {
    /// SQL NULL.
    Null,
    /// Signed integer.
    Int(i64),
    /// Unsigned integer.
    UInt(u64),
    /// Double-precision float.
    Float(f64),
    /// Boolean (backends without a boolean type send 0 / 1).
    Bool(bool),
    /// Text.
    Str(String),
    /// Binary data.
    Bytes(Vec<u8>),
}

fn map_serde(e: serde_json::Error) -> OrmError {
    OrmError::TypeConversion(e.to_string())
}

/// An entity field's JSON value as the parameter for its column.
pub fn json_to_param(v: &serde_json::Value, col: &ColumnDef) -> Param {
    match v {
        serde_json::Value::Null => Param::Null,
        serde_json::Value::Bool(b) => Param::Bool(*b),
        serde_json::Value::Number(n) => {
            if col.col_type == ColumnType::Float {
                Param::Float(n.as_f64().unwrap_or(0.0))
            } else if let Some(i) = n.as_i64() {
                Param::Int(i)
            } else if let Some(u) = n.as_u64() {
                Param::UInt(u)
            } else {
                Param::Float(n.as_f64().unwrap_or(0.0))
            }
        }
        serde_json::Value::String(s) => Param::Str(s.clone()),
        serde_json::Value::Array(items) if col.col_type == ColumnType::Binary => {
            Param::Bytes(items.iter().map(|v| v.as_u64().unwrap_or(0) as u8).collect())
        }
        other => Param::Str(serde_json::to_string(other).unwrap_or_default()),
    }
}

fn scalar_to_param(v: &serde_json::Value) -> Result<Param, OrmError> {
    Ok(match v {
        serde_json::Value::Null => Param::Null,
        serde_json::Value::Bool(b) => Param::Bool(*b),
        serde_json::Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                Param::Int(i)
            } else if let Some(u) = n.as_u64() {
                Param::UInt(u)
            } else {
                Param::Float(n.as_f64().unwrap_or(0.0))
            }
        }
        serde_json::Value::String(s) => Param::Str(s.clone()),
        other => {
            return Err(OrmError::TypeConversion(format!(
                "value must be a scalar (number/string/bool), got {other}"
            )))
        }
    })
}

/// A primary key's parameters: one for a scalar key, several (in declaration
/// order) for a composite (tuple) key.
pub fn id_to_params<Id: Serialize>(id: &Id) -> Result<Vec<Param>, OrmError> {
    match serde_json::to_value(id).map_err(map_serde)? {
        serde_json::Value::Array(parts) => parts.iter().map(scalar_to_param).collect(),
        scalar => Ok(vec![scalar_to_param(&scalar)?]),
    }
}

/// The column for an entity field (by field or column name).
pub fn column_for_field<T: Entity>(field: &str) -> Option<&'static ColumnDef> {
    T::columns().iter().find(|c| c.field == field || c.name == field)
}

/// A stringly-typed filter value as a parameter typed by its column, so
/// `"42"` compares as a number against a numeric column.
pub fn filter_param<T: Entity>(field: &str, value: &str) -> Param {
    let Some(col) = column_for_field::<T>(field) else {
        return Param::Str(value.to_string());
    };
    match col.col_type {
        ColumnType::Boolean => match value {
            "true" | "1" => Param::Bool(true),
            "false" | "0" => Param::Bool(false),
            _ => Param::Str(value.to_string()),
        },
        ColumnType::Integer | ColumnType::BigInt => value
            .parse::<i64>()
            .map(Param::Int)
            .or_else(|_| value.parse::<u64>().map(Param::UInt))
            .unwrap_or_else(|_| Param::Str(value.to_string())),
        ColumnType::Float => value.parse::<f64>().map(Param::Float).unwrap_or_else(|_| Param::Str(value.to_string())),
        _ => Param::Str(value.to_string()),
    }
}

/// The primary-key column names (`["id"]` if the entity declares none).
pub fn pk_cols<T: Entity>() -> Vec<&'static str> {
    let cols: Vec<&'static str> = T::columns().iter().filter(|c| c.primary_key).map(|c| c.name).collect();
    if cols.is_empty() {
        vec!["id"]
    } else {
        cols
    }
}

/// Whether the entity's key is generated by the database.
pub fn is_auto_pk<T: Entity>() -> bool {
    T::columns().iter().any(|c| c.primary_key && c.auto)
}

/// Whether this entity is a fresh row with a generated key still at 0.
pub fn is_new_auto_entity<T>(entity: &T) -> Result<bool, OrmError>
where
    T: Entity + Serialize,
    T::Id: Serialize,
{
    if !is_auto_pk::<T>() {
        return Ok(false);
    }
    let v = serde_json::to_value(entity.id()).map_err(map_serde)?;
    Ok(matches!(v, serde_json::Value::Number(ref n) if n.as_u64() == Some(0) || n.as_i64() == Some(0)))
}

/// The entity as a JSON object of its fields.
pub(crate) fn entity_object<T: Serialize>(entity: &T) -> Result<serde_json::Map<String, serde_json::Value>, OrmError> {
    serde_json::to_value(entity)
        .map_err(map_serde)?
        .as_object()
        .cloned()
        .ok_or_else(|| OrmError::TypeConversion("entity must serialize as a JSON object".into()))
}
