#!/usr/bin/env python3
"""Render an acceptance report from a feature catalog and a `cargo test` log.

usage: report.py <db title> <catalog> <cargo test log> <meta.json>  > report.md
Exit status 1 when any evidence test failed, was skipped, or did not run.
"""
import json
import re
import sys
from collections import OrderedDict

title, catalog_path, log_path, meta_path = sys.argv[1:5]
meta = json.load(open(meta_path))

# --- test results ---------------------------------------------------------
results = OrderedDict()
cur = None
for raw in open(log_path, encoding="utf-8", errors="replace"):
    line = raw.rstrip("\n")
    m = re.match(r"^test (\S+) \.\.\. ?(.*)$", line)
    if m:
        cur = m.group(1)
        results[cur] = {"status": None, "out": []}
        rest = m.group(2).strip()
        if rest in ("ok", "FAILED") or rest.startswith("ignored"):
            results[cur]["status"] = rest.split()[0]
        elif rest:
            results[cur]["out"].append(rest)
        continue
    if cur and results[cur]["status"] is None:
        s = line.strip()
        if s in ("ok", "FAILED") or s.startswith("ignored"):
            results[cur]["status"] = s.split()[0]
        else:
            results[cur]["out"].append(line)

def test_status(name):
    r = results.get(name)
    if r is None:
        return "NOT RUN"
    if r["status"] == "ok" and any(re.match(r"(?i)^\s*skip\b", l) for l in r["out"]):
        return "SKIPPED"
    return {"ok": "PASS", "FAILED": "FAIL", "ignored": "IGNORED"}.get(r["status"], "NO RESULT")

# --- catalog ----------------------------------------------------------------
features = []
for raw in open(catalog_path, encoding="utf-8"):
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    area, feature, evidence = [p.strip() for p in line.split("|", 2)]
    features.append((area, feature, evidence))

ICON = {"PASS": "✅ PASS", "FAIL": "❌ FAIL", "GAP": "🚧 GAP", "N/A": "➖ N/A"}
rows = []
used = set()
counts = {"PASS": 0, "FAIL": 0, "GAP": 0, "N/A": 0}
for area, feature, evidence in features:
    if evidence.startswith("GAP:") or evidence.startswith("N/A:"):
        kind = "GAP" if evidence.startswith("GAP:") else "N/A"
        note = evidence.split(":", 1)[1].strip()
        for t in re.findall(r"— ([a-z0-9_:]+)\)?$", note):
            used.add(t)
        rows.append((area, feature, kind, note))
        counts[kind] += 1
        continue
    tests = [t.strip() for t in evidence.split(",") if t.strip()]
    states = [(t, test_status(t)) for t in tests]
    used.update(tests)
    ok = all(s == "PASS" for _, s in states)
    detail = "<br>".join(f"`{t}`" + ("" if s == "PASS" else f" **{s}**") for t, s in states)
    kind = "PASS" if ok else "FAIL"
    counts[kind] += 1
    rows.append((area, feature, kind, detail))

all_status = {name: test_status(name) for name in results}
tests_total = len(all_status)
by = lambda s: sum(1 for v in all_status.values() if v == s)
unmapped = [n for n in results if n not in used]
bad_evidence = counts["FAIL"] > 0
complete = counts["PASS"] + counts["GAP"] + counts["FAIL"]

# --- render ---------------------------------------------------------------
out = []
w = out.append
w(f"# {title} — acceptance report")
w("")
container = meta.get("container", "")
if container.startswith("none (native"):
    where = "real servers running natively"
elif container.startswith("servers in Docker"):
    where = "real servers in Docker"
elif container.startswith("none"):
    where = "real database files (embedded engine)"
else:
    where = "the database in Docker"
w("> Generated by `acceptance/run.sh` from a real test run against")
w(f"> {where}. Do not edit by hand: re-run the script.")
w("")
w("| | |")
w("|---|---|")
for k in ["generated", "server", "image", "container", "driver commit", "rustc", "command"]:
    if k in meta:
        w(f"| {k} | {meta[k]} |")
w("")
verdict = "PASSED" if not (bad_evidence or any(v != "PASS" for v in all_status.values())) else "FAILED"
w(f"## Verdict: implemented features **{verdict}** · completeness **{counts['PASS']}/{complete}**"
  + (" — NOT complete" if counts["GAP"] else " — complete"))
w("")
w("- *Implemented features* passes only if every test ran and passed (no skips) in this run.")
w("- *Completeness* counts 🚧 gaps (listed below) against the full feature catalog.")
w(f"- Features verified: **{counts['PASS']} / {complete}** "
  f"({counts['GAP']} not implemented yet, {counts['FAIL']} failing; {counts['N/A']} not applicable to {title}).")
w(f"- Tests run: {tests_total} — {by('PASS')} passed, {by('FAIL')} failed, "
  f"{by('SKIPPED')} skipped (a skip is a failure here: the environment was incomplete), {by('IGNORED')} ignored.")
w("- A feature is ✅ only when every test listed as its evidence ran and passed in this run.")
w("")
area = None
for a, feature, kind, detail in rows:
    if a != area:
        area = a
        w(f"## {a}")
        w("")
        w("| Feature | Status | Evidence / note |")
        w("|---|---|---|")
    w(f"| {feature} | {ICON[kind]} | {detail} |")
    nxt = rows.index((a, feature, kind, detail)) + 1
    if nxt == len(rows) or rows[nxt][0] != a:
        w("")
problems = [(n, s) for n, s in all_status.items() if s != "PASS"]
if problems:
    w("## Tests that did not pass")
    w("")
    for n, s in problems:
        w(f"### `{n}` — {s}")
        w("")
        w("```")
        w("\n".join(results[n]["out"][-40:]) or "(no output)")
        w("```")
        w("")
w("## All tests in this run")
w("")
w("| Test | Result | Mapped to a feature |")
w("|---|---|---|")
for n, s in all_status.items():
    w(f"| `{n}` | {s} | {'yes' if n in used else 'no'} |")
w("")
print("\n".join(out))
sys.exit(1 if (bad_evidence or problems) else 0)
