#!/usr/bin/env python3
"""Collect every `GAP:` row of the acceptance catalogs into docs/GAPS.md, the
one list of what the drivers do not do (yet), for users to read and request.

usage: acceptance/gaps.py           # rewrite docs/GAPS.md
       acceptance/gaps.py --check   # exit 1 if docs/GAPS.md is out of date

The catalogs (acceptance/<db>.features) are the source; this file is derived.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "GAPS.md"


def title(path):
    first = path.read_text(encoding="utf-8").splitlines()[0]
    m = re.match(r"#\s*(.+?) feature catalog", first)
    return m.group(1) if m else path.stem


def kind(note):
    n = note.lower()
    if "not verified" in n or n.startswith("implemented") or "built and unit-tested" in n:
        return "Built, not verified"
    if "refused with a clear error" in n:
        return "Refused with a clear error"
    return "Not built"


def esc(s):
    return s.replace("|", "\\|")


def render():
    drivers = []
    for path in sorted((ROOT / "acceptance").glob("*.features")):
        gaps, total = [], 0
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            area, feature, evidence = [p.strip() for p in line.split("|", 2)]
            if evidence.startswith("N/A:"):
                continue
            total += 1
            if evidence.startswith("GAP:"):
                gaps.append((area, feature, evidence[4:].strip()))
        drivers.append((path.stem, title(path), total, gaps))

    n = sum(len(g) for *_, g in drivers)
    out = [
        "# Known gaps",
        "",
        "<!-- Generated by acceptance/gaps.py from acceptance/*.features — do not edit by hand. -->",
        "",
        "Every feature a driver does not do, or does without proof against a real",
        "server, is listed here. Everything else in the catalogs passed its",
        "acceptance run (see [`docs/acceptance/`](acceptance/)). Nothing is",
        "left out to make the numbers look better.",
        "",
        "*Tóm tắt: danh sách mọi tính năng driver chưa làm, hoặc đã làm nhưng chưa",
        "kiểm chứng được với server thật. Cần tính năng nào thì yêu cầu theo",
        "hướng dẫn cuối trang.*",
        "",
        "| Status | Meaning |",
        "|---|---|",
        "| Not built | The driver does not do it (or does part of it, as the note says). |",
        "| Refused with a clear error | Asking for it fails at once with an error that names it; nothing hangs or misbehaves. |",
        "| Built, not verified | The code exists, but the test setup has no server or platform to prove it against. |",
        "",
        f"**{n} gaps** across {sum(1 for *_, g in drivers if g)} drivers.",
        "",
        "| Driver | Features | Gaps |",
        "|---|---:|---:|",
    ]
    for stem, name, total, gaps in drivers:
        out.append(f"| [{esc(name)}](#{stem}) | {total} | {len(gaps) or '—'} |")
    for stem, name, total, gaps in drivers:
        if not gaps:
            continue
        out += ["", f'<a id="{stem}"></a>', f"## {name}", "",
                f"Report: [`docs/acceptance/{stem}.md`](acceptance/{stem}.md) · catalog: `acceptance/{stem}.features`", "",
                "| Area | Feature | Status | Why / what happens instead |", "|---|---|---|---|"]
        for area, feature, note in gaps:
            out.append(f"| {esc(area)} | {esc(feature)} | {kind(note)} | {esc(note)} |")
    out += [
        "",
        "## Requesting a gap",
        "",
        "Open an issue titled `gap: <driver> — <feature>` (the feature as written",
        "above) and say what you need it for: the deployment, the server version,",
        "and how often it matters. A concrete use case decides the order.",
        "",
        "A gap is closed in this order:",
        "",
        "1. build it, with tests against a real server (Docker or a native install),",
        "2. name those tests as the row's evidence in `acceptance/<db>.features`",
        "   (replacing `GAP: …`),",
        "3. rerun `acceptance/run.sh <db>`; the report and this page update.",
        "",
        "*Yêu cầu: mở issue tên `gap: <driver> — <tính năng>` kèm lý do cần (môi",
        "trường, phiên bản server). Một GAP chỉ được xoá khi có test với server thật",
        "làm bằng chứng.*",
        "",
    ]
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/GAPS.md is out of date: run acceptance/gaps.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


sys.exit(main())
